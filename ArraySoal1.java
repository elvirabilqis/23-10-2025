public class ArraySoal1 {
    public static void main(String[] args) {
        // Menyimpan 7 nama kota 
        String[] kota = {"Jakarta", "Bandung", "Surabaya", "Tulungagung", "Medan", "Yogyakarta", "Bekasi"};

        // Menampilkan semua nama kota
        System.out.println("Daftar Nama Kota");
        for (int i = 0; i < kota.length; i++) {
            System.out.println(kota[i]);
    }
}
}